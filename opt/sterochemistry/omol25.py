# Dataset building helpers
# ------------------------


def _discover_splits(root: Path) -> dict[str, list[str]]:
    """Find input .aselmdb files and group them into splits.

    Rules:
    - If ``root`` is a file ending with .aselmdb -> one split named 'train'.
    - If ``root`` is a directory with ``*.aselmdb`` -> one split named after the
      directory (commonly a split name like 'neural_val'). If the directory name
      is 'train'/'validation'/'test', keep it, otherwise default to 'train'.
    - If ``root`` contains subdirectories, each subdirectory with ``*.aselmdb``
      becomes a split named by the subdirectory.
    """
    if root.is_file() and root.suffix == ".aselmdb":
        return {root.stem: [str(root)]}

    if root.is_dir():
        # Case 1: directory has *.aselmdb directly
        files_here = sorted(str(p) for p in root.glob("*.aselmdb"))
        if files_here:
            return {root.name: files_here}

        # Case 2: subdirectories are splits
        splits: dict[str, list[str]] = {}
        for sub in sorted([p for p in root.iterdir() if p.is_dir()]):
            files = sorted(str(p) for p in sub.glob("*.aselmdb"))
            if files:
                splits[sub.name] = files
        return splits

    return {}


def _entries_from_files(files: list[str]):
    for f in files:
        for entry in iter_aselmdb(f):
            yield {"raw": json.dumps(entry)}


OUTPUT_COLUMNS = [
    "unique_id",
    "composition",
    "SMILES",
    "InChI",
    "InChIKey",
    "total-energy",
    "homo",
    "lumo",
    "gap",
    "charge",
    "spin",
    "nl_energy",
    "atomic-numbers",
    "atomic-coordinates",
    "atomic-isotope",
    "bond-connections",
    "bond-orders",
    "mulliken_charges",
    "lowdin_charges",
    "nbo_charges",
]


def _process_batch(batch: dict) -> dict:
    raws: list[str] = batch["raw"]
    out: dict[str, list] = {k: [] for k in OUTPUT_COLUMNS}
    keep: list[bool] = []
    for s in raws:
        try:
            rec = record_from_entry(json.loads(s))
        except Exception:
            rec = None
        if rec is None:
            # Fill placeholders; we'll filter later
            for k in OUTPUT_COLUMNS:
                # Scalars -> None, lists -> empty list
                if k in {
                    "atomic-numbers",
                    "atomic-coordinates",
                    "atomic-isotope",
                    "bond-connections",
                    "bond-orders",
                    "mulliken_charges",
                    "lowdin_charges",
                    "nbo_charges",
                }:
                    out[k].append([])
                else:
                    out[k].append(None)
            keep.append(False)
        else:
            for k in OUTPUT_COLUMNS:
                out[k].append(rec.get(k))
            keep.append(True)

    out["__keep__"] = keep
    return out


def _build_split_dataset(files: list[str], num_proc: int) -> Dataset:
    # Stage 1: build a lightweight dataset of raw JSON strings
    ds = Dataset.from_generator(
        _entries_from_files,
        gen_kwargs={"files": files},
        keep_in_memory=False,
    )

    # Stage 2: heavy processing in parallel
    ds = ds.map(
        _process_batch,
        batched=True,
        remove_columns=["raw"],
        num_proc=max(1, int(num_proc)),
        desc="Processing records with RDKit",
    )

    # Stage 3: drop failed rows
    ds = ds.filter(lambda keep: keep, input_columns=["__keep__"]).remove_columns(
        ["__keep__"]
    )
    return ds


if __name__ == "__main__":
    raise SystemExit(main())
